// watchdog 子命令的实现：install / uninstall / status / run。
// 与 lib/watchdog.mjs 分开：那个文件 import 即运行守护循环，不能给 CLI 复用。
//
// 安装形态：Windows 启动文件夹放一个 VBS（用户级、免管理员、删文件即卸载），
// 由它在登录时以隐藏窗口拉起看门狗。node 用安装时解析出的**绝对路径**
// （`where node` 的第一命中，退回当前进程的 node），不依赖登录会话的 PATH。
import fs from 'node:fs'
import path from 'node:path'
import os from 'node:os'
import { spawn, spawnSync } from 'node:child_process'
import { DATA_DIR, HOST_HOME, PLUGIN_ROOT } from './paths.mjs'

const WATCHDOG_SCRIPT = path.join(PLUGIN_ROOT, 'lib', 'watchdog.mjs')
const LOCK_FILE = path.join(DATA_DIR, 'watchdog.json')
// VBS 文件名带插件名：用户翻启动文件夹时能认出是谁的。
// 导出给 lib/migrate.mjs（迁移预检报「启动文件夹里两只 VBS 的归属」）。
export const VBS_NAME = 'fox-widget-watchdog.vbs'

// 导出给 lib/migrate.mjs（迁移引导要报「启动文件夹里两只 VBS 的归属」）：
// 只读路径拼接，不做任何文件操作。
export function startupDir() {
  const appData = process.env.APPDATA || path.join(os.homedir(), 'AppData', 'Roaming')
  return path.join(appData, 'Microsoft', 'Windows', 'Start Menu', 'Programs', 'Startup')
}

export function vbsFile() {
  return path.join(startupDir(), VBS_NAME)
}

// 解析登录时能用的 node 绝对路径。VBS 由 wscript 执行，吃不到安装会话的
// 环境变量与 PATH 增项，所以必须落绝对路径。优先**宿主目录之外**的 node：
// 宿主注入 PATH 后 `where node` 的第一命中常是它自带的版本化目录
//（~/.workbuddy/binaries/node/versions/<版本>/），宿主升级后该路径会消失；
// 登录会话的 PATH 里也未必有它。都没有时退回当前进程的 node。
export function resolveNodeBin() {
  if (process.env.FOX_WIDGET_NODE) return process.env.FOX_WIDGET_NODE
  try {
    const r = spawnSync('where', ['node'], { encoding: 'utf8', windowsHide: true, timeout: 8000 })
    const hits = String((r && r.stdout) || '')
      .split(/\r?\n/)
      .map((s) => s.trim())
      .filter(Boolean)
      .filter((p) => fs.existsSync(p))
    const homeLower = String(HOST_HOME).toLowerCase()
    const stable = hits.find((p) => p.toLowerCase().indexOf(homeLower) === -1)
    if (stable) return stable
    if (hits[0]) return hits[0]
  } catch (err) {}
  return process.execPath
}

function readLock() {
  try {
    const v = JSON.parse(fs.readFileSync(LOCK_FILE, 'utf8'))
    return v && typeof v === 'object' ? v : null
  } catch (err) {
    return null
  }
}

function pidAlive(pid) {
  const n = Number(pid)
  if (!Number.isInteger(n) || n <= 0) return false
  try {
    process.kill(n, 0)
    return true
  } catch (err) {
    return err && err.code === 'EPERM'
  }
}

export function watchdogRunning() {
  const lock = readLock()
  return lock && pidAlive(lock.pid) ? lock : null
}

// 启动项内容：不接受「安装时把绝对路径写死」的写法——插件副本装在
// <cache>/<市场>/<插件>/<版本>/ 下，升级后版本目录会变，写死的旧路径会静默失效。
// 改为每次登录**解析最新安装副本**（按目录修改时间取最新的一份，兜底用安装时的
// 路径），这样升级插件不必重装启动项。
// node 同理：机器上只有宿主自带 node 时，录下的路径是宿主版本化目录
// （~/.workbuddy/binaries/node/versions/<版本>/node.exe），宿主升级后就没了——
// 所以录制路径不存在时，现场在宿主 node 目录里挑最新的一份。
function vbsContent(nodeBin, fallbackScript) {
  // 扫描基准目录：**只有 cache 布局**（<...>/cache/<市场>/<插件名>/<版本>/）才扫
  // 兄弟版本目录挑最新；仓库/本地市场布局（marketplace.json 的 source:"./" 就是
  // 该形态，README 也指导在仓库里跑 watchdog install）的 dirname 是仓库父目录，
  // 扫兄弟目录没有意义——直接用当前副本路径，升级 = 仓库内拉新，录制的路径不变。
  //（2026-10-14 审查 P2-B：此前无条件 dirname，仓库形态下会去扫 Worktrees 的
  // 兄弟目录。）
  let base = path.dirname(PLUGIN_ROOT)
  try {
    const selfName = String(
      JSON.parse(fs.readFileSync(path.join(PLUGIN_ROOT, '.codebuddy-plugin', 'plugin.json'), 'utf8')).name || ''
    )
    if (!selfName || path.basename(base) !== selfName) base = PLUGIN_ROOT
  } catch (err) {
    base = PLUGIN_ROOT // 清单读不到：保守起见按仓库形态处理
  }
  const nodeVersionsDir = path.join(HOST_HOME, 'binaries', 'node', 'versions')
  const lines = [
    "' fox-widget watchdog: keeps the widget alive alongside WorkBuddy.",
    "' Auto-generated by `node lib/cli.mjs watchdog install`; delete this file to disable.",
    "' At logon it picks the newest installed plugin copy, so updating the plugin",
    "' does not break this startup entry.",
    'Set fso = CreateObject("Scripting.FileSystemObject")',
    'Set sh = CreateObject("WScript.Shell")',
    'base = "' + base + '"',
    'fallbackScript = "' + fallbackScript + '"',
    'script = ""',
    'bestTime = #1/1/2000#',
    'If fso.FolderExists(base) Then',
    '  For Each d In fso.GetFolder(base).SubFolders',
    '    p = d.Path & "\\lib\\watchdog.mjs"',
    '    If fso.FileExists(p) Then',
    '      If d.DateLastModified > bestTime Then',
    '        bestTime = d.DateLastModified',
    '        script = p',
    '      End If',
    '    End If',
    '  Next',
    'End If',
    'If script = "" Then script = fallbackScript',
    'nodeBin = "' + nodeBin + '"',
    'If Not fso.FileExists(nodeBin) Then',
    '  nodeBase = "' + nodeVersionsDir + '"',
    '  nodeTime = #1/1/2000#',
    '  If fso.FolderExists(nodeBase) Then',
    '    For Each nd In fso.GetFolder(nodeBase).SubFolders',
    '      np = nd.Path & "\\node.exe"',
    '      If fso.FileExists(np) Then',
    '        If nd.DateLastModified > nodeTime Then',
    '          nodeTime = nd.DateLastModified',
    '          nodeBin = np',
    '        End If',
    '      End If',
    '    Next',
    '  End If',
    'End If',
    'sh.Run """" & nodeBin & """ """ & script & """", 0, False',
  ]
  return lines.join('\r\n') + '\r\n'
}

function startWatchdogNow(nodeBin) {
  const child = spawn(nodeBin, [WATCHDOG_SCRIPT], {
    detached: true,
    stdio: 'ignore',
    windowsHide: true,
  })
  child.unref()
  return child.pid
}

// 启动项 VBS 的落盘编码（纯函数，抽出来是为了能直接测）。
//
// **Windows Script Host 只认 ANSI 与 UTF-16 的 BOM（FF FE / FE FF），不认 UTF-8 的
// BOM。** 这里以前写的是 `'\ufeff' + 内容` 配 `'utf8'`（注释还写着「wscript 按 BOM
// 识别编码」——那个假设是错的），于是文件以 `EF BB BF` 开头，wscript 按 ANSI 读，
// 头三个字节成了非法字符，登录时弹：
//
//   Windows Script Host
//   脚本: C:\Users\<用户>\AppData\Roaming\Microsoft\Windows\Start Menu\Programs\Startup\fox-widget-watchdog.vbs
//   行: 1  字符: 1   错误: 无效字符   代码: 800A0408
//
// 而且**一句都不执行**（编译期失败）→「自启」等于没装，用户只能在登录后手动
// 起看门狗。2026-10-14 真机复现（用户直接被弹窗糊脸）；顺带发现机器上那个看门狗
// 因此一直是手动起的，而那次手动安装落在**管理员终端**里，把看门狗与它派生的
// 服务/浮层全带成了管理员权限（见 MEMORY.md 的权限雷）。
//
// 现在两条路：内容全 ASCII → 写**无 BOM 的 ANSI**（兼容性最好，野生 .vbs 的常态）；
// 含非 ASCII（用户名/安装路径里有中文等）→ 写 UTF-16LE + BOM（这个 BOM 它是认的）。
export function vbsFileEncoding(body) {
  return /^[\x00-\x7f]*$/.test(String(body))
    ? { encoding: 'latin1', bom: '' }
    : { encoding: 'utf16le', bom: '\ufeff' }
}

// 写启动项 VBS。抽成独立函数，便于安装流程与「只重写文件」两种场景复用。
export function installWatchdogVbs() {
  const nodeBin = resolveNodeBin()
  try {
    fs.mkdirSync(startupDir(), { recursive: true })
    const body = vbsContent(nodeBin, WATCHDOG_SCRIPT)
    // 编码必须挑对，否则整个自启静默失效（长注释见下面的 vbsFileEncoding）。
    const enc = vbsFileEncoding(body)
    fs.writeFileSync(vbsFile(), enc.bom + body, enc.encoding)
  } catch (err) {
    return { ok: false, error: String((err && err.message) || err), nodeBin }
  }
  return { ok: true, file: vbsFile(), nodeBin }
}

export function cmdWatchdogInstall() {
  if (process.platform !== 'win32') {
    console.log('watchdog 目前只支持 Windows（启动文件夹 VBS）。')
    return 1
  }
  const r = installWatchdogVbs()
  const nodeBin = r.nodeBin
  if (!r.ok) {
    console.log('写入启动项失败：' + r.error)
    return 1
  }
  console.log('✅ 看门狗已装进启动文件夹：')
  console.log('   ' + r.file)
  console.log('   node：' + nodeBin)
  const running = watchdogRunning()
  if (running) {
    console.log('🐳 看门狗已在运行（pid ' + running.pid + '），无需重复启动')
  } else {
    const pid = startWatchdogNow(nodeBin)
    console.log('🐳 看门狗已启动（pid ' + pid + '）——本机 WorkBuddy 正在跑的话，挂件马上就位')
  }
  console.log('   卸载：node lib/cli.mjs watchdog uninstall')
  return 0
}

export function cmdWatchdogUninstall() {
  const file = vbsFile()
  let removed = false
  try {
    if (fs.existsSync(file)) {
      fs.unlinkSync(file)
      removed = true
    }
  } catch (err) {
    console.log('删除启动项失败：' + String((err && err.message) || err))
    return 1
  }
  const running = watchdogRunning()
  if (running) {
    // Windows 下没有跨进程的优雅 SIGTERM；直接结束。锁文件会留下陈旧 pid，
    // 下次启动按「pid 不活」自愈，不影响。
    try {
      spawnSync('taskkill', ['/PID', String(running.pid), '/T', '/F'], { windowsHide: true, timeout: 8000 })
    } catch (err) {}
    console.log('🐳 看门狗进程已结束（pid ' + running.pid + '）')
  }
  console.log(removed ? '✅ 已从启动文件夹移除看门狗（重启登录后不再自启）' : '启动项本来就不存在（没装过或已卸载）')
  console.log('   挂件服务与浮层不受影响；下次 WorkBuddy 里做会话动作时钩子仍会拉起它们')
  return 0
}

export async function cmdWatchdogStatus() {
  const installed = fs.existsSync(vbsFile())
  const running = watchdogRunning()
  console.log('看门狗自启：' + (installed ? '已安装（' + vbsFile() + '）' : '未安装（node lib/cli.mjs watchdog install）'))
  console.log('看门狗进程：' + (running ? '运行中（pid ' + running.pid + '，' + (running.startedAt || '') + ' 起）' : '未运行'))
  return 0
}

export async function cmdWatchdogRun() {
  if (watchdogRunning()) {
    console.log('看门狗已在运行（pid ' + watchdogRunning().pid + '），不再重复启动')
    return 0
  }
  // 前台运行（排障用）：Ctrl+C 直接结束
  const r = spawnSync(resolveNodeBin(), [WATCHDOG_SCRIPT], { stdio: 'inherit', timeout: 24 * 3600 * 1000 })
  return (r && r.status) || 0
}
